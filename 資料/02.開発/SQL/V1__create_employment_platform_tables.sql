    measured_value NUMERIC(18,4),
    fired_at TIMESTAMPTZ NOT NULL,
    acknowledged_by_user_id BIGINT REFERENCES m_user(user_id),
    acknowledged_at TIMESTAMPTZ,
    resolved_at TIMESTAMPTZ,
    note TEXT
